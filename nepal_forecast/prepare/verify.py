Q100_AREAS = (200, 500, 1000)   # km2, for the table of 100-year floods by method
STORM_CHECK_DHM = ["283.3", "286", "363", "364", "390", "460", "465", "470", "485", "580",
                   "581", "585", "728", "795", "550.05", "640", "505", "530"]


def _q100(m, a):
    return {"WECS/DHM 1990": F.wecs_dhm_1990(a, 100), "DHM 2004": F.dhm_2004(a, 100),
            "MHSP 1997 (western)": F.mhsp_1997(a, 100, "western"),
            "WECS 2019 specific": F.wecs_2019_specific(a, 100),
            "Modified Dickens": F.modified_dickens(a, 100), "Dickens C=11": F.dickens(a, 11),
            "Dickens C=14": F.dickens(a, 14), "Inglis": F.inglis(a)}[m]


def run(static_dir, out_md):
    st = pd.read_csv(os.path.join(static_dir, "stations.csv"), dtype={"dhm": str})
    r = st.area_ratio
    lines = ["# Verification", "",
             "Generated by `nepal-forecast prepare verify` from the files in `static/`.", "",
             "## 1. Traced drainage areas against the DHM stations", "",
             "Each of the 112 DHM hydrometric stations (DHM list of July 2025) is "
             "snapped to the traced river within 1.8 km whose upstream area matches the "
             "published drainage area best.", "",
             f"* within 5%: **{int((abs(r - 1) <= .05).sum())}** of {len(st)} stations",
             f"* within 10%: **{int((abs(r - 1) <= .10).sum())}**",
             f"* within 20%: **{int((abs(r - 1) <= .20).sum())}**",
             f"* median absolute difference: **{np.median(abs(r - 1)) * 100:.1f}%**", "",
             "Stations more than 10% off:", "",
             "| DHM | River | Location | Published km² | Traced km² | Ratio |",
             "|---|---|---|---:|---:|---:|"]
    for _, s in st[abs(r - 1) > 0.10].iterrows():
        lines.append(f"| {s.dhm} | {s.river} | {s.location} | {s.area_km2:,.1f} | "
                     f"{s.area_traced_km2:,.1f} | {s.area_ratio:.2f} |")
    lines += ["", "The three Arun stations are about 15% larger than published. The traced "
              "Arun (Pumqu) basin reaches 88.9° E, the eastern limit given for the Pumqu basin "
              "in the literature (about 25,300 km² in China), so the difference most likely "
              "lies in the older DHM delineation of the Tibetan plateau part; it carries "
              "into Saptakoshi at Chatara (+8%).", "",
              "<details><summary>All 112 stations</summary>", "",
              "| DHM | River | Location | Published km² | Traced km² | Ratio | Moved km |",
              "|---|---|---|---:|---:|---:|---:|"]
    for _, s in st.iterrows():
        lines.append(f"| {s.dhm} | {s.river} | {s.location} | {s.area_km2:,.1f} | "
                     f"{s.area_traced_km2:,.1f} | {s.area_ratio:.2f} | {s.moved_km:.2f} |")
    lines += ["", "</details>", "", "## 2. Basins as traced", "",
              "River systems as they leave Nepal, with their traced drainage areas.", "",
              "| Basin | Traced km² |", "|---|---:|"]
    b = json.load(open(os.path.join(static_dir, "basins.geojson")))
    got = {f["properties"]["name"]: f["properties"]["area_km2"] for f in b["features"]}
    for name, a in sorted(got.items(), key=lambda kv: -kv[1]):
        if not name.startswith("River system at"):
            lines.append(f"| {name} | {a:,.0f} |")
    lines += ["", "Mechi, Tinau and Mahakali meet the border before their outlet: the traced basin "
              "stops where the river first leaves Nepal's territory. The traced Karnali includes "
              "the Mohana system, which joins it at the border; Saptakosi includes the Arun from Tibet.", "",
              "## 3. 100-year floods by method", "",
              "100-year floods (m³/s), A₃₀₀₀ = A, no snow, MHSP western region; computed by "
              "`nepal_forecast/formulas.py` (also checked in `tests/test_formulas.py`).", "",
              "| Method | " + " | ".join(f"{a:,} km²" for a in Q100_AREAS) + " |",
              "|---|---:|---:|---:|"]
    for m in ("WECS/DHM 1990", "DHM 2004", "MHSP 1997 (western)", "WECS 2019 specific",
              "Modified Dickens", "Dickens C=11", "Dickens C=14", "Inglis"):
        cells = [f"{_q100(m, a):,.0f}" for a in Q100_AREAS]
        lines.append(f"| {m} | " + " | ".join(cells) + " |")
    tg = pd.read_csv(os.path.join(static_dir, "targets.csv"), dtype={"station": str}, keep_default_na=False)
    k = tg[tg.station == "283.3"]
    if len(k):
        k = k.iloc[0]
        lines += ["", "## 4. Kandra River at Pahalmanpur (DHM 283.3), as traced", "",
                  f"Area {k.area_km2} km² (published 199.38), mean elevation {k.elev_mean_m} m, "
                  f"longest flow path {k.flow_length_km} km with a drop of {k.drop_m} m, Kirpich "
                  f"t_c = {k.tc_h} h ({k.tc_h * 60:.0f} min), C = {k.c_rational}, "
                  f"CN(II) = {k.cn2}, MWI = {k.mwi_mm} mm, AWI = {k.awi_mm} mm."]
    lines += design_storm_check(static_dir, st)
    lines += climate_check()
    os.makedirs(os.path.dirname(out_md), exist_ok=True)
    with open(out_md, "w") as f:
        f.write("\n".join(lines) + "\n")
    return out_md


def design_storm_check(static_dir, st):
    """What uniform 24-hour storm (after 60 mm of rain three days before, so
    AMC III) lifts the SCS-CN + unit hydrograph peak to the 2- and 100-year
    floods of the regional formulas? Coherent methods need about the 2- and
    100-year one-day rainfall of the place."""
    from datetime import datetime, timedelta
    from .. import config, cycle, hydrograph as H
    cfg = config.load("/nonexistent.yaml")
    net = cycle.Network(static_dir)
    t = net.targets
    pick = st[st.dhm.isin(STORM_CHECK_DHM)].target.tolist()
    pick = sorted(set(pick))
    desc = {k: v[pick] for k, v in net.desc().items()}
    _, thr, _ = cycle.design_thresholds(net, cfg)
    thr = thr[pick]
    now = datetime(2026, 8, 10)
    times = [now + timedelta(hours=k) for k in range(1, 24 * 10 + 1)]
    depths = np.arange(10, 1001, 10.0)
    peaks = []
    for p in depths:
        r = np.zeros((len(pick), len(times)))
        r[:, 60:72] = 5.0
        r[:, 120:144] = p / 24.0
        peaks.append(H.simulate(r, times, desc, cfg)["scs"][:, 100:].max(axis=1))
    peaks = np.array(peaks)
    out = ["", "## 5. Design-storm consistency of the rainfall method and the flood levels", "",
           "The uniform 24-hour storm (after 60 mm three days before: AMC III) that lifts the "
           "SCS-CN + unit-hydrograph peak to the 2- and 100-year floods of the regional "
           "formulas (median of the methods), at selected Chure and hill stations. "
           "For coherent methods these depths should be near the 2- and 100-year one-day "
           "rainfall of the place (roughly 80-150 mm and 250-450 mm in Nepal's hills and Chure).", "",
           "| DHM | River | Area km² | t_c h | CN(II) | Q2 m³/s | storm for Q2 | Q100 m³/s | storm for Q100 |",
           "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for j, i in enumerate(pick):
        s = st[st.target == i].iloc[0]
        p2 = np.interp(thr[j, 0], peaks[:, j], depths)
        p100 = np.interp(thr[j, -1], peaks[:, j], depths)
        out.append(f"| {s.dhm} | {s.river} | {t.area_km2[i]:,.0f} | {t.tc_h[i]:.1f} | {t.cn2[i]:.0f} | "
                   f"{thr[j, 0]:,.0f} | {p2:.0f} mm | {thr[j, -1]:,.0f} | {p100:.0f} mm |")
    return out


# Approximate long-term annual rainfall at DHM stations (rounded; for orientation)
STATION_NORMALS = {"Kathmandu airport": (27.70, 85.36, 1500), "Pokhara airport": (28.20, 83.98, 3900),
                   "Dhangadhi (Kailali)": (28.69, 80.60, 1900), "Biratnagar": (26.48, 87.26, 1900),
                   "Jumla": (29.27, 82.18, 800), "Jomsom (Mustang)": (28.78, 83.72, 260)}


def climate_check():
    from .common import CACHE
    from .network import CLIMATE_FILE
    p = os.path.join(CACHE, "climate.npz")
    if not os.path.exists(p):
        p = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
                         "static", CLIMATE_FILE)
    if not os.path.exists(p):
        return []
    c = np.load(p)
    out = ["", "## 6. The ERA5 rainfall climatology (MWI, AWI)", "",
           "ERA5 2019-2023 annual rain at the 0.25 deg cell of some DHM stations, against their "
           "approximate long-term normals. ERA5 is close on the plains but **too wet over the "
           "hills and mountains** (a known ERA5 bias in the Himalaya). MWI and AWI enter only the "
           "monthly-flow formulas (the base flow): with WECS/DHM 1990 (MWI^0.25-0.39) a two-fold "
           "excess raises the base flow by about 20-30%; DHM 2004 (AWI^0.47-0.76) is more "
           "affected. A gauge-based climatology (DHM normals, APHRODITE or CHIRPS) written into "
           "`prepare_cache/climate.npz` and `nepal-forecast prepare network` would correct it.", "",
           "| Station | ERA5 annual mm | Approx. normal mm | Ratio |", "|---|---:|---:|---:|"]
    for name, (la, lo, obs) in STATION_NORMALS.items():
        i, j = int(np.argmin(abs(c["lat"] - la))), int(np.argmin(abs(c["lon"] - lo)))
        v = float(c["annual"][i, j])
        out.append(f"| {name} | {v:,.0f} | {obs:,} | {v / obs:.1f} |")
    return out
